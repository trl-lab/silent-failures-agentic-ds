#!/usr/bin/env python3
"""Failure-mode taxonomy table for the appendix: our FM01-FM15 ids/names (same as everywhere else in
the paper -- see judge_viz_common. FM_LABEL) paired with a one-sentence definition.

Usage:
    python scripts/visualization/build_fm_taxonomy_table.py
    -> results/fm_taxonomy_table.tex
"""
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(PROJECT_ROOT / "scripts"))
from judge_viz_common import FM_LABEL, FM_DISPLAY_ORDER  # noqa: E402

OUT_PATH = PROJECT_ROOT / "results" / "fm_taxonomy_table.tex"

# json_key -> (definition, source). "master" = Lones 2024 / Kumar 2025 table
# (as pasted, matched by content); "project" = no match in that table --
# definition instead taken from judge_spec.py's own FAILURE_MODES (the
# real judge-prompt text), lightly trimmed for a one-sentence table cell.
DEFINITIONS = {
    "FM01": (
        "The agent frames the modelling problem in a way that discards signal the task "
        "actually provides -- e.g. collapsing a survival/time-to-event problem into plain "
        "binary classification, or ignoring an explicit multi-target structure.",
        "project",
    ),
    "FM02": (
        "Exploring test data during initial analysis creates untestable assumptions baked "
        "into model design.",
        "master",
    ),
    "FM03": (
        "Ignoring data duplication, missing values, and outliers/inconsistencies before "
        "model building.",
        "master",
    ),
    "FM04": (
        "Performing mean/median imputation before splitting -- leaks test statistics into "
        "training.",
        "master",
    ),
    "FM05": (
        "Randomly splitting time-series data without respecting temporal order -- "
        "introduces look-ahead bias.",
        "master",
    ),
    "FM06": (
        "Model trained and evaluated on the same data -- performance is a misleading "
        "overestimate.",
        "master",
    ),
    "FM07": (
        "The agent uses raw columns as-is (at most basic imputation/encoding) with no "
        "derived features or domain-informed transforms, even where the task or column "
        "names suggest obvious ones.",
        "project",
    ),
    "FM08": (
        "Fitting scaler on the full dataset before splitting -- test statistics leak into "
        "training.",
        "master",
    ),
    "FM09": (
        "Selecting features on the full dataset before splitting -- causes test leakage.",
        "master",
    ),
    "FM10": (
        "Using a regression model for a classification task (or vice versa) -- conceptual "
        "mismatch.",
        "master",
    ),
    "FM11": (
        "Training deep learning models without dropout or weight decay -- prone to "
        "overfitting.",
        "master",
    ),
    "FM12": (
        "When the agent combines multiple models, it uses an unweighted/equal-weight "
        "average or simple majority vote with no tuning of the combination itself, where a "
        "more sophisticated combination is straightforward given what's already computed.",
        "project",
    ),
    "FM13": (
        "Same test set used to select among multiple models -- test set gradually leaks "
        "into model selection (sequential overfitting).",
        "master",
    ),
    "FM14": (
        "Single evaluation of a stochastic/unstable model; results may not reflect true "
        "performance.",
        "master",
    ),
    "FM15": (
        "Single metric gives an incomplete picture; different metrics reveal different "
        "failure modes.",
        "master",
    ),
}
assert set(DEFINITIONS) == set(FM_DISPLAY_ORDER)


def escape_tex(s: str) -> str:
    return s.replace("&", "\\&").replace("_", "\\_").replace("%", "\\%")


def main():
    lines = []
    lines.append("% Auto-generated by scripts/visualization/build_fm_taxonomy_table.py -- do not hand-edit.")
    lines.append("% Ids/names match judge_viz_common.FM_LABEL (used everywhere else")
    lines.append("% in the paper). Definitions: Lones 2024 / Kumar 2025 master taxonomy for 12")
    lines.append("% modes with a direct content match; judge_spec.py's own definition for the")
    lines.append("% 3 project-specific additions (marked with a dagger).")
    lines.append("\\begin{table}[t]")
    lines.append("\\centering")
    lines.append("\\small")
    lines.append("\\begin{tabular}{@{}llp{9.5cm}@{}}")
    lines.append("\\toprule")
    lines.append("\\textbf{ID} & \\textbf{Failure Mode} & \\textbf{Definition} \\\\")
    lines.append("\\midrule")

    for fid in FM_DISPLAY_ORDER:
        definition, source = DEFINITIONS[fid]
        dagger = "$^\\dagger$" if source == "project" else ""
        lines.append(f"{fid} & {escape_tex(FM_LABEL[fid])}{dagger} & "
                      f"{escape_tex(definition)} \\\\")

    lines.append("\\bottomrule")
    lines.append("\\end{tabular}")
    lines.append(
        "\\caption{The 15 failure modes used in this work. $^\\dagger$ = project-specific "
        "addition not present in the Lones (2024) / Kumar (2025) source taxonomy; its "
        "definition is our own.}"
    )
    lines.append("\\label{tab:fm-taxonomy}")
    lines.append("\\end{table}")

    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUT_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUT_PATH}")


if __name__ == "__main__":
    main()
