"""
Per-config breakdown of judge v3 findings: judged pipelines (agent x model x
task runs, no_code excluded), total "present" findings across the 16
FAILURE_MODES, and avg findings per judged pipeline -- one row per (agent,
model), same numbers behind plot_failure_mode_distribution.py's n=5823/n=2397
totals broken out by config instead of pooled.

Same multirow-per-agent scaffolding as build_judge_heatmap_table_by_agent.py.

Usage:
    python scripts/visualization/build_findings_per_pipeline_table.py
    -> results/findings_per_pipeline_table.tex
"""
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(PROJECT_ROOT / "scripts"))
from judge_viz_common import AGENTS, MODELS, AGENT_DISPLAY, load_agent_model  # noqa: E402

# Local reorder/drop (qwen first, gemini-3.6-flash out), matching plot_findings_per_pipeline.py;
# doesn't touch judge_viz_common.MODELS.
MODELS = [m for m in MODELS if m["key"] != "gemini-3.6-flash"]
MODELS = sorted(MODELS, key=lambda m: 0 if "qwen" in m["key"].lower() else 1)

OUT_PATH = PROJECT_ROOT / "results" / "findings_per_pipeline_table.tex"


def escape_tex(s: str) -> str:
    return s.replace("&", "\\&").replace("_", "\\_").replace("%", "\\%")


def config_stats(agent: str, model: str) -> dict:
    tasks = load_agent_model(agent, model)
    n_judged = 0
    n_findings = 0
    for t in tasks.values():
        if t["no_code"]:
            continue
        n_judged += 1
        n_findings += sum(1 for c in t["cells"] if c["s"] == "present")
    return {"n_judged": n_judged, "n_findings": n_findings,
            "avg": n_findings / n_judged if n_judged else float("nan")}


def main() -> None:
    lines = []
    lines.append("% Auto-generated by scripts/visualization/build_findings_per_pipeline_table.py -- do not hand-edit.")
    lines.append("% Judged pipelines = agent x model x task runs with no_code excluded (see")
    lines.append("% judge_viz_common.load_agent_model). Findings = count of 'present' cells across")
    lines.append("% the 16 FAILURE_MODES. Same totals as plot_failure_mode_distribution.py, by config.")
    lines.append("\\begin{table}[t]")
    lines.append("\\centering")
    lines.append("\\small")
    lines.append("\\begin{tabular}{llrrr}")
    lines.append("\\toprule")
    lines.append("\\textbf{Agent} & \\textbf{Model} & \\textbf{Judged} & \\textbf{Findings} & "
                  "\\textbf{Avg / pipeline} \\\\")
    lines.append("\\midrule")

    total_judged = 0
    total_findings = 0
    for ai, agent in enumerate(AGENTS):
        agent_rows = []
        for m in MODELS:
            s = config_stats(agent, m["key"])
            total_judged += s["n_judged"]
            total_findings += s["n_findings"]
            agent_rows.append(
                f" & {escape_tex(m['label'])} & {s['n_judged']} & {s['n_findings']} & {s['avg']:.2f} \\\\"
            )
        lines.append(f"\\multirow{{{len(MODELS)}}}{{*}}{{\\textbf{{{escape_tex(AGENT_DISPLAY[agent])}}}}} ")
        lines[-1] += agent_rows[0]
        lines.extend(agent_rows[1:])
        if ai < len(AGENTS) - 1:
            lines.append("\\midrule")

    lines.append("\\midrule")
    lines.append(f"\\multicolumn{{2}}{{l}}{{\\textbf{{Total}}}} & {total_judged} & {total_findings} & "
                  f"{total_findings / total_judged:.2f} \\\\")
    lines.append("\\bottomrule")
    lines.append("\\end{tabular}")
    lines.append(
        "\\caption{Judged pipelines, total detected failure instances, and average findings "
        "per judged pipeline, by agent and model.}"
    )
    lines.append("\\label{tab:findings-per-pipeline}")
    lines.append("\\end{table}")

    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUT_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUT_PATH}")


if __name__ == "__main__":
    main()
