#!/usr/bin/env python3
"""Dataset characteristics tables (for the appendix, so no header abbreviations): (1) one row per
source -- task count, task-type breakdown, size (median rows / median features); (2) domain
distribution, as its own table since domains cut across source and don't align as extra columns on
(1).

Usage:
    python scripts/visualization/build_dataset_characteristics_table.py
    -> results/dataset_characteristics_table.tex
"""
import csv
import glob
import json
import statistics
import sys
from collections import defaultdict
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent
OUT_PATH = PROJECT_ROOT / "results" / "dataset_characteristics_table.tex"

SOURCE_LABEL = {
    "kaggle": "Kaggle",
    "mlebench": "MLE-bench",
    "openml": "OpenML",
    "strable": "STRABLE",
    "uci": "UCI",
}
SOURCE_ORDER = ["kaggle", "mlebench", "openml", "strable", "uci"]


def escape_tex(s: str) -> str:
    return s.replace("&", "\\&").replace("_", "\\_").replace("%", "\\%")


def main():
    ids = {r["task_id"] for r in csv.DictReader(open(PROJECT_ROOT / "results" / "predictive_scores.csv"))}

    metas = {}
    for f in glob.glob(str(PROJECT_ROOT / "datasets" / "**" / "task.json"), recursive=True):
        try:
            d = json.loads(Path(f).read_text())
        except Exception:
            continue
        if d["id"] in ids:
            d["_bucket"] = Path(f).relative_to(PROJECT_ROOT / "datasets").parts[0]
            metas[d["id"]] = d

    ms = list(metas.values())
    by_bucket = defaultdict(list)
    for d in ms:
        by_bucket[d["_bucket"]].append(d)

    lines = []
    lines.append("% Auto-generated by scripts/visualization/build_dataset_characteristics_table.py -- do not hand-edit.")
    lines.append(f"% Computed from the {len(ms)} tasks actually used in the benchmark (matched against")
    lines.append("% unique task_id values in results/predictive_scores.csv), not every task.json under")
    lines.append("% datasets/ (595 candidate files exist; most were never selected).")
    lines.append("\\begin{table}[t]")
    lines.append("\\centering")
    lines.append("\\begin{tabular}{@{}lrrrrrr@{}}")
    lines.append("\\toprule")
    lines.append("\\textbf{Source} & \\textbf{Tasks} & \\textbf{Regression} & \\textbf{Binary Classification} & "
                  "\\textbf{Multi-class Classification} & \\textbf{Median Rows} & \\textbf{Median Features} \\\\")
    lines.append("\\midrule")

    tot_n = tot_reg = tot_bin = tot_multi = 0
    all_rows, all_feats = [], []
    for src in SOURCE_ORDER:
        group = by_bucket.get(src, [])
        n = len(group)
        # multi_output_regression counts as regression too -- it's still a
        # regression task, just with several continuous targets instead of one.
        reg = sum(1 for d in group if d.get("task_type") in ("regression", "multi_output_regression"))
        bin_c = sum(1 for d in group if d.get("task_type") == "b-classification")
        multi_c = sum(1 for d in group if d.get("task_type") == "m-classification")
        rows = [d["n_rows"] for d in group if d.get("n_rows")]
        feats = [d["n_features"] for d in group if d.get("n_features") is not None]
        med_rows = f"{int(statistics.median(rows)):,}" if rows else "--"
        med_feats = f"{int(statistics.median(feats)):,}" if feats else "--"
        lines.append(f"{SOURCE_LABEL[src]} & {n} & {reg} & {bin_c} & {multi_c} & "
                      f"{med_rows} & {med_feats} \\\\")
        tot_n += n; tot_reg += reg; tot_bin += bin_c; tot_multi += multi_c
        all_rows += rows; all_feats += feats

    lines.append("\\midrule")
    med_rows_all = f"{int(statistics.median(all_rows)):,}"
    med_feats_all = f"{int(statistics.median(all_feats)):,}"
    lines.append(f"\\textbf{{Total}} & {tot_n} & {tot_reg} & {tot_bin} & {tot_multi} & "
                  f"{med_rows_all} & {med_feats_all} \\\\")
    lines.append("\\bottomrule")
    lines.append("\\end{tabular}")
    lines.append(
        "\\caption{Dataset characteristics across the 220 benchmark tasks, by source. "
        "\\textbf{Regression} includes one multi-output regression task (Kaggle: "
        "\\texttt{open-problems-single-cell-perturbations}). Row/feature counts are "
        "medians (feature counts exclude the target column).}"
    )
    lines.append("\\label{tab:dataset-characteristics}")
    lines.append("\\end{table}")
    lines.append("")

    # --- Domain distribution, as its own table (domains cut across source,
    # so they don't align cleanly as extra columns on the table above). ---
    dom = defaultdict(int)
    for d in ms:
        dom[d.get("domain", "unknown")] += 1
    dom_order = sorted(dom.items(), key=lambda kv: -kv[1])

    lines.append("\\begin{table}[t]")
    lines.append("\\centering")
    lines.append("\\begin{tabular}{@{}lr@{}}")
    lines.append("\\toprule")
    lines.append("\\textbf{Domain} & \\textbf{Tasks} \\\\")
    lines.append("\\midrule")
    for name, count in dom_order:
        lines.append(f"{escape_tex(name.capitalize())} & {count} \\\\")
    lines.append("\\midrule")
    lines.append(f"\\textbf{{Total}} & {sum(dom.values())} \\\\")
    lines.append("\\bottomrule")
    lines.append("\\end{tabular}")
    lines.append("\\caption{Domain distribution across the 220 benchmark tasks.}")
    lines.append("\\label{tab:dataset-domains}")
    lines.append("\\end{table}")

    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUT_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUT_PATH}")


if __name__ == "__main__":
    main()
