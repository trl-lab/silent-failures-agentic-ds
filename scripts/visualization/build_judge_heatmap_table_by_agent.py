"""LaTeX heatmap table of failure-mode rates by agent and model. Each cell is
compute_taxonomy_column_applicable's present/applicable rate (see its docstring in
judge_viz_common.py: dividing by applicable pipelines avoids diluting gated modes whose
precondition is rare).

Usage: python scripts/visualization/build_judge_heatmap_table_by_agent.py
-> results/judge_by_agent_fm_x_heatmap.tex
"""
import sys
from pathlib import Path

import matplotlib
import matplotlib.colors as mcolors

sys.path.insert(0, str(Path(__file__).resolve().parent))
from judge_viz_common import (  # noqa: E402
    PROJECT_ROOT, AGENTS, MODELS, FAILURE_MODES, AGENT_DISPLAY,
    compute_taxonomy_column_applicable, FM_LABEL,
)

# Below this many applicable pipelines, a present/applicable rate is too noisy
# to trust (single-digit denominators can swing 10+ points on one task) --
# render grey "N/A" instead of a real number. 20 is a judgment call, not a
# statistically derived cutoff; revisit if reviewers want a formal rationale.
MIN_APPLICABLE = 20

OUT_PATH = PROJECT_ROOT / "results" / "judge_by_agent_fm_x_heatmap.tex"

# Qwen-first model order with gemini-3.6-flash dropped (local rebind, doesn't touch
# judge_viz_common.MODELS). \multirow{{len(MODELS)}}
# below picks up the row count automatically, so dropping a model here also
# correctly shrinks each agent's row span from 4 to 3.
MODELS = [m for m in MODELS if m["key"] != "gemini-3.6-flash"]
MODELS = sorted(MODELS, key=lambda m: 0 if "qwen" in m["key"].lower() else 1)

TAXONOMY_ORDER = [
    "FM01", "FM02", "FM03", "FM04", "FM05", "FM06",
    "FM07", "FM08", "FM09", "FM10", "FM11", "FM12",
    "FM13", "FM14", "FM15",
]
_fid_to_idx = {fid: i for i, (fid, _, _) in enumerate(FAILURE_MODES)}
ORDER_IDX = [_fid_to_idx[fid] for fid in TAXONOMY_ORDER]
assert set(TAXONOMY_ORDER) <= {fid for fid, _, _ in FAILURE_MODES}, \
    "TAXONOMY_ORDER has an id not present in FAILURE_MODES"
assert len(TAXONOMY_ORDER) == len(set(TAXONOMY_ORDER)), "TAXONOMY_ORDER has a duplicate"

CMAP = matplotlib.colormaps["OrRd"]
NO_DATA_HEX = "D9D9D9"  # flat gray, matches the bar chart's "no data yet" gray text color family


def value_to_hex(v: float) -> str:
    # sqrt scale, not linear -- see module docstring. Exact 0.0 is
    # special-cased to pure white (OrRd(0) is a pale cream, #FFF7EC, not
    # #FFFFFF) rather than relying on sqrt(0)==0 to land on the colormap's
    # own endpoint color.
    if v <= 0.0:
        return "FFFFFF"
    r, g, b, _ = CMAP(v ** 0.5)
    return mcolors.to_hex((r, g, b))[1:].upper()


def text_color_for(hex_bg: str) -> str:
    """Black text on light cells, white text on dark cells -- simple relative
    luminance threshold, standard heatmap-table readability trick."""
    r, g, b = (int(hex_bg[i:i + 2], 16) / 255 for i in (0, 2, 4))
    luminance = 0.299 * r + 0.587 * g + 0.114 * b
    return "000000" if luminance > 0.55 else "FFFFFF"


def cell_tex(value: float | None, placeholder: str = "--") -> str:
    if value is None:
        return f"\\cellcolor[HTML]{{{NO_DATA_HEX}}}{{\\color[HTML]{{666666}}{placeholder}}}"
    hexcol = value_to_hex(value)
    textcol = text_color_for(hexcol)
    return f"\\cellcolor[HTML]{{{hexcol}}}{{\\color[HTML]{{{textcol}}}{value:.2f}}}"


def escape_tex(s: str) -> str:
    return s.replace("&", "\\&").replace("_", "\\_").replace("%", "\\%")


def main() -> None:
    n_cols = len(TAXONOMY_ORDER)
    col_spec = "ll" + "c" * n_cols
    any_no_data = False
    any_low_n = False

    lines = []
    lines.append("% Auto-generated by scripts/visualization/build_judge_heatmap_table_by_agent.py -- do not hand-edit.")
    lines.append("% Cells are compute_taxonomy_column_applicable's present/applicable rate")
    lines.append("% (NOT the bar chart's present/n_judged -- see script docstring), same")
    lines.append("% qwen-first model order.")
    lines.append("% Requires in the parent document's preamble:")
    lines.append("%   \\usepackage[table]{xcolor}")
    lines.append("%   \\usepackage{booktabs}")
    lines.append("%   \\usepackage{multirow}")
    lines.append("%   \\usepackage{graphicx}")
    lines.append("\\begin{table*}[t]")
    lines.append("\\centering")
    lines.append("\\scriptsize")
    lines.append("\\setlength{\\tabcolsep}{1.5pt}")
    lines.append(f"\\begin{{tabular}}{{{col_spec}}}")
    lines.append("\\toprule")

    header_cells = " & \n".join(
        f"\\rotatebox{{75}}{{\\tiny {escape_tex(FM_LABEL[fid])}}}" for fid in TAXONOMY_ORDER
    )
    lines.append(f"\\textbf{{Agent}} & \\textbf{{Model}} & \n{header_cells} \\\\")
    lines.append("\\midrule")

    for ai, agent in enumerate(AGENTS):
        agent_rows = []
        for mi, m in enumerate(MODELS):
            model_id, model_label = m["key"], m["label"]
            col = compute_taxonomy_column_applicable(agent, model_id)
            if col["n_judged"] == 0:
                any_no_data = True
                row_cells = " & ".join(cell_tex(None) for _ in TAXONOMY_ORDER)
            else:
                cells = []
                for fi in range(n_cols):
                    idx = ORDER_IDX[fi]
                    n_app = col["n_applicable"][idx]
                    if n_app < MIN_APPLICABLE:
                        any_low_n = True
                        cells.append(cell_tex(None, placeholder="N/A"))
                    else:
                        cells.append(cell_tex(col["rates"][idx]))
                row_cells = " & ".join(cells)
            agent_rows.append(f" & {escape_tex(model_label)} & {row_cells} \\\\")
        lines.append(f"\\multirow{{{len(MODELS)}}}{{*}}{{\\textbf{{{escape_tex(AGENT_DISPLAY[agent])}}}}} ")
        lines[-1] += agent_rows[0]
        lines.extend(agent_rows[1:])
        if ai < len(AGENTS) - 1:
            lines.append("\\midrule")

    lines.append("\\bottomrule")
    lines.append("\\end{tabular}")
    no_data_note = " ``--'' marks a cell with no judged tasks yet." if any_no_data else ""
    low_n_note = (
        f" Grey ``N/A'' marks a cell with fewer than {MIN_APPLICABLE} applicable "
        "pipelines (rate not meaningful at that sample size)." if any_low_n else ""
    )
    lines.append(
        "\\caption{Per-failure-mode presence rate, CONDITIONED on applicability "
        "(present / applicable, not present / all judged tasks -- see \\S\\ref{sec:judge}) "
        "by agent and model. Cell background scales white ($0.0$) to dark red ($1.0$). "
        "HPO without nested CV is omitted: applicable to only 2.2\\% of pipelines "
        "project-wide, too sparse for a meaningful column here."
        f"{low_n_note}{no_data_note}}}"
    )
    lines.append("\\label{tab:judge-by-agent-fm-x-heatmap}")
    lines.append("\\end{table*}")

    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUT_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUT_PATH}")


if __name__ == "__main__":
    main()
